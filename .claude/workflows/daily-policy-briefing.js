// ============================================================
// 每日政策简报抓取工作流
// 并行搜索多个信源，速度比逐个搜索快3-5倍
// ============================================================

phase('搜索信源')

log('🚀 开始并行搜索官方信源...')

// 并行搜索所有信源
const [results1, results2, results3, results4, results5, results6, results7] = await parallel([
  () => agent('搜索求是杂志(qstheory.cn) 最新一期的重要内容，包括头条文章、经济、文化等栏目的核心政策文章。列出标题和核心要点。', {
    label: '求是杂志',
    phase: '搜索信源',
  }),
  () => agent('搜索人民日报(people.com.cn) 最近2-3天最新的头版要闻、评论版(人民时评)、经济版、科技版、民生版的重要政策文章。列出标题和核心要点。', {
    label: '人民日报',
    phase: '搜索信源',
  }),
  () => agent('搜索新华社(xinhuanet.com) 最近2-3天最新的权威发布、新华时评、经济参考等栏目的重要政策新闻。列出标题和核心要点。', {
    label: '新华社',
    phase: '搜索信源',
  }),
  () => agent('搜索国务院政策文件库(www.gov.cn) 最近一周最新发布的政策文件、政策解读、新闻发布会内容。列出标题和核心要点。', {
    label: '国务院文件',
    phase: '搜索信源',
  }),
  () => agent('搜索农业农村部(moa.gov.cn) 最近一周最新的农业政策、粮食安全、乡村振兴相关的重要政策文件。列出标题和核心要点。', {
    label: '农业农村部',
    phase: '搜索信源',
  }),
  () => agent('搜索科技部(most.gov.cn) 最近一周最新的科技政策、创新驱动、科研改革相关的重要政策文件。列出标题和核心要点。', {
    label: '科技部',
    phase: '搜索信源',
  }),
  () => agent('搜索国家发改委(ndrc.gov.cn) 最近一周最新的宏观经济、产业政策、价格政策相关的重要文件。列出标题和核心要点。', {
    label: '发改委',
    phase: '搜索信源',
  }),
])

// 过滤掉搜索失败的结果
const allResults = [results1, results2, results3, results4, results5, results6, results7].filter(Boolean)

log(`✅ 搜索完成，共收集到 ${allResults.length} 个信源的结果`)

// ============================================================
// 第二步：整理生成简报
// ============================================================
phase('整理简报')

const briefing = await agent(`你是资深政策智库分析师。请根据以下从7个官方信源搜索到的原始内容，整理一份格式规范的每日政策简报。

要求：
1. 筛选出最重要的5-8条政策动态，覆盖不少于3个领域（经济/科技/农业/民生/生态）
2. 每条包含：领域分类、信源、核心事实、关键数据、民生关联点、解读潜力评级
3. 语言通俗有力，杜绝公文腔
4. 按重要性排序，最重要的放前面
5. 简报日期用今天
	6. 在所有简报条目的最后，加上一句："哥哥，以上是今天的政策简报，你想深度解读哪一条？告诉我编号或标题，我帮你写成详细的材料报告和PPT！"

原始搜索内容如下：

${allResults.map((r, i) => `--- 信源 ${i + 1} ---\n${r}`).join('\n\n')}

请按以下格式输出：

# 今日日期 政策与宏观动态简报

### 1. 【领域】标题
- **信源**：来源
- **政策背景/核心事实**：(100字以内)
- **关键数据/提法**：核心指标、新概念
- **民生/行业关联点**：对普通人/企业的影响
- **解读潜力评级**：★★★★☆

...（共5-8条）
`, {
  label: '整理简报',
  phase: '整理简报',
})

return briefing
