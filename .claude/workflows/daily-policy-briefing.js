  description: '并行抓取多个官方信源，快速生成每日政策与宏观动态简报。比逐个手动搜索快3-5倍。',
  whenToUse: '每天16:00自动运行，也可手动说"跑daily-policy-briefing"或"整理今日政策简报"',
  phases: [
    { title: '搜索信源', detail: '并行搜索人民日报、求是、新华社、国务院、部委政策' },
    { title: '整理简报', detail: '汇总、去重、评级，生成结构化简报' },
    { title: '询问需求', detail: '询问用户想深度解读哪条政策' },
  ],
